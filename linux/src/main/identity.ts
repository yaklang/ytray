import { YTrayError } from './errors'
import type { BrowserKind } from '../shared/types'

/** Port of DockBadgeLabel: 1..702 → A..ZZ. */
export function defaultBadge(ordinal: number): string {
  let value = Math.max(1, ordinal)
  let result = ''
  do {
    value -= 1
    result = String.fromCharCode(65 + (value % 26)) + result
    value = Math.floor(value / 26)
  } while (value > 0)
  return result
}

export function normalizeBadge(input: string): string {
  const value = input.trim().toUpperCase()
  if (!/^[A-Z]{1,2}$/.test(value)) {
    throw new YTrayError('launchFailed', 'Dock 角标只能是 1–2 个英文字母')
  }
  return value
}

export interface RGB {
  r: number
  g: number
  b: number
}

/** Same palette as BrowserIdentityColor in the macOS/Windows builds. */
const palette: RGB[] = [
  { r: 242, g: 98, b: 21 },
  { r: 37, g: 99, b: 235 },
  { r: 22, g: 163, b: 74 },
  { r: 124, g: 58, b: 237 },
  { r: 190, g: 24, b: 93 },
  { r: 15, g: 118, b: 110 }
]

export function identityColor(badge: string): RGB {
  const label = normalizeBadge(badge)
  let ordinal = 0
  for (const letter of label) ordinal = ordinal * 26 + letter.charCodeAt(0) - 64
  return palette[(ordinal - 1) % palette.length] as RGB
}

export function identityColorHex(badge: string): string {
  const { r, g, b } = identityColor(badge)
  return `#${[r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('')}`
}

/** Higher-contrast label colour, same threshold as the macOS/Windows palettes. */
export function identityForegroundHex(badge: string): string {
  const { r, g, b } = identityColor(badge)
  const linear = (component: number): number => {
    const value = component / 255
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4
  }
  const luminance = 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b)
  return luminance > 0.179 ? '#1b120a' : '#ffffff'
}

export function identityThemeArgument(badge: string): string {
  const { r, g, b } = identityColor(badge)
  return `--install-autogenerated-theme=${r},${g},${b}`
}

/** WM_CLASS used for per-instance window grouping on X11 and most Wayland compositors. */
export function windowClass(badge: string): string {
  return `YTray-${normalizeBadge(badge)}`
}

const titles: Record<BrowserKind, string> = {
  chrome: 'Google Chrome',
  chromeBeta: 'Chrome Beta',
  chromeCanary: 'Chrome Canary',
  chromeForTesting: 'Chrome for Testing',
  chromium: 'Chromium',
  edge: 'Microsoft Edge'
}

export function browserKindTitle(kind: BrowserKind): string {
  return titles[kind]
}

export function inferBrowserKind(name: string, executablePath: string): BrowserKind {
  const value = `${name} ${executablePath}`.toLowerCase()
  if (value.includes('for testing') || value.includes('chrome-for-testing')) return 'chromeForTesting'
  if (value.includes('canary') || value.includes('unstable')) return 'chromeCanary'
  if (value.includes('beta')) return 'chromeBeta'
  if (value.includes('microsoft-edge') || value.includes('msedge') || value.includes('/edge')) return 'edge'
  if (value.includes('chromium')) return 'chromium'
  return 'chrome'
}
